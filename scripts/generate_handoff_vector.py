"""Writes the shared key-handoff test vector.

The web app (hoermoles-ble, `spa/packages/hoermoles-ble-js/src/handoff.ts`)
implements the client side of the envelope in WebCrypto; this vector pins both
implementations to the same bytes. ECDH involves randomness on both sides, so
the HA key, the client key and the nonce are derived from fixed seeds here.

    PYTHONPATH=. uv run python scripts/generate_handoff_vector.py [copy-to ...]

Writes tests/fixtures/handoff_vector.json and, if given, the same file to each
extra path (the web app's copy lives at shared/handoff-vectors.json).
"""

from __future__ import annotations

import hashlib
import json
import sys
from pathlib import Path

from cryptography.hazmat.primitives.asymmetric import ec
from hoermoles_ble import BundleEntry, Credentials, encode_bundle

from custom_components.hoermoles_ble.handoff import (
    HandoffSession,
    b64url_encode,
    encrypt_envelope,
    public_key_bytes,
)

FIXTURE = Path(__file__).resolve().parent.parent / "tests" / "fixtures" / "handoff_vector.json"


def _key(seed: bytes) -> ec.EllipticCurvePrivateKey:
    return ec.derive_private_key(int.from_bytes(hashlib.sha256(seed).digest()), ec.SECP256R1())


def _scalar(key: ec.EllipticCurvePrivateKey) -> str:
    return key.private_numbers().private_value.to_bytes(32, "big").hex()


def build() -> dict:
    ha_key = _key(b"hoermoles-handoff-vector-ha")
    client_key = _key(b"hoermoles-handoff-vector-client")
    nonce = hashlib.sha256(b"hoermoles-handoff-vector-nonce").digest()[:12]
    token = b64url_encode(hashlib.sha256(b"hoermoles-handoff-vector-token").digest())
    address = "F1:26:AF:CC:41:86"

    session = HandoffSession(address=address, token=token, _private_key=ha_key)
    credentials = Credentials(device_address=address, root_id=291, root_key=bytes(range(32)), created_unix=1784850177)
    plaintext = encode_bundle([BundleEntry(credentials=credentials)])
    envelope = encrypt_envelope(session.public_key, token, plaintext.encode(), client_key=client_key, nonce=nonce)

    assert session.accept(b64url_encode(envelope)).credentials == credentials
    return {
        "_comment": (
            "Generated by hoermoles-ble-homeassistant scripts/generate_handoff_vector.py - do not edit by hand. "
            "Byte strings are lowercase hex. Both copies (HA repo tests/fixtures/handoff_vector.json, "
            "hoermoles-ble shared/handoff-vectors.json) must stay identical."
        ),
        "qr_link": session.qr_data("http://192.168.1.10:8123", "Home"),
        "ha_url": f"http://192.168.1.10:8123{session.path}",
        "token": token,
        "address": address,
        "ha_private_scalar": _scalar(ha_key),
        "ha_public": session.public_key.hex(),
        "client_private_scalar": _scalar(client_key),
        "client_public": public_key_bytes(client_key.public_key()).hex(),
        "nonce": nonce.hex(),
        "plaintext": plaintext,
        "envelope": envelope.hex(),
        "delivery_url": f"http://192.168.1.10:8123{session.path}#p={b64url_encode(envelope)}",
    }


def main() -> None:
    text = json.dumps(build(), indent=2) + "\n"
    for target in [FIXTURE, *map(Path, sys.argv[1:])]:
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(text)
        print(f"wrote {target}")


if __name__ == "__main__":
    main()
